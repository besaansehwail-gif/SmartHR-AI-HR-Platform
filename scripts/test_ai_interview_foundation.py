"""AI Interview - Phase 1 (voice foundation) tests. No network, no LiveKit.

    venv\\Scripts\\python.exe -m scripts.test_ai_interview_foundation

What this proves without a LiveKit project:

1. **Configuration precedence** - environment -> `.env.local` -> `.env`, an
   empty value counts as absent, and the status report names missing
   variables but never contains a value.
2. **The token** - minted with a throwaway key/secret generated by this test
   and verified with LiveKit's own `TokenVerifier`: one room, microphone +
   camera (Stage 4A),
   no data publishing, no metadata, no PII, a 10-minute lifetime, and the
   interviewer dispatched by name.
3. **The HTTP layer** - a server of its own on port 8043, given fake LiveKit
   variables through the *environment* (which outranks `.env.local`, so this
   machine's real credentials are never read): anonymous 401, staff 403 on
   `/session`, Manager/Employee 403 on `/status`, an applicant 200 with a
   verifiable token, and a fresh room per session.
4. **Not configured** - the service refuses with `not_configured`, which the
   router maps to 503.
5. **Containment** - nothing in `app/ai/interview/` imports the database.

What it does NOT prove - that needs real credentials and is what
`scripts/verify_ai_interview_voice.py` is for: that LiveKit accepts the
token, that the agent is dispatched, and that STT, GPT-4o and TTS answer.
"""

