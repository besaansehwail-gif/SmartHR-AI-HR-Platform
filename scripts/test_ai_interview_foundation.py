#: Throwaway credentials that exist only for this run. They are not a real
#: LiveKit project's and are never printed.
FAKE_URL = "wss://smarthr-test.invalid"
FAKE_KEY = "APItest" + secrets.token_hex(4)
FAKE_SECRET = secrets.token_urlsafe(32)

passed = 0
failed: list[str] = []


def check(name: str, ok: bool, detail: str = "") -> bool:
    global passed
    if ok:
        passed += 1
        print(f"  PASS  {name}")
    else:
        failed.append(f"{name}{f' - {detail}' if detail else ''}")
        print(f"  FAIL  {name}{f' - {detail}' if detail else ''}")
    return bool(ok)


def section(title: str) -> None:
    print(f"\n{title}\n{'-' * len(title)}")


class Server:
    """A uvicorn for this test alone, with fake LiveKit variables."""

    def __init__(self, port: int):
        self.port = port
        self._process: subprocess.Popen | None = None

    def __enter__(self) -> "Server":
        self._process = subprocess.Popen(
            [sys.executable, "-m", "uvicorn", "app.main:app",
             "--port", str(self.port), "--log-level", "warning"],
            cwd=str(ROOT),
            env={
                **os.environ,
                "LIVEKIT_URL": FAKE_URL,
                "LIVEKIT_API_KEY": FAKE_KEY,
                "LIVEKIT_API_SECRET": FAKE_SECRET,
                # Phase 5 warms a CV parse per session; no model in this suite.
                "SMARTHR_LLM_PROVIDER": "none",
            },
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )

        for _ in range(80):
            try:
                with urllib.request.urlopen(f"http://127.0.0.1:{self.port}/", timeout=2):
                    return self
            except urllib.error.HTTPError:
                return self
            except Exception:
                time.sleep(0.25)

        raise SystemExit(f"The test server on port {self.port} did not start.")

    def __exit__(self, *_exc) -> None:
        if self._process is not None:
            self._process.terminate()
            try:
                self._process.wait(timeout=10)
            except subprocess.TimeoutExpired:  # pragma: no cover
                self._process.kill()


def test_config() -> None:
    section("1. Configuration precedence")
    from app.ai.interview import config

    saved = {name: os.environ.pop(name, None) for name in config.LIVEKIT_VARIABLES}
    try:
        with tempfile.TemporaryDirectory() as tmp:
            local = Path(tmp) / ".env.local"
            local.write_text(
                "LIVEKIT_URL=wss://from-local.invalid\n"
                "LIVEKIT_API_KEY=local-key\n"
                "LIVEKIT_API_SECRET=\n",
                encoding="utf-8",
            )

            s = config.voice_settings(local_file=local)
            check("value read from .env.local", s.livekit_url == "wss://from-local.invalid")
            check("empty value in .env.local counts as absent", "LIVEKIT_API_SECRET" in s.missing)
            check("not configured while one variable is missing", s.configured is False)

            os.environ["LIVEKIT_URL"] = "wss://from-env.invalid"
            s = config.voice_settings(local_file=local)
            check("real environment outranks .env.local", s.livekit_url == "wss://from-env.invalid")

            os.environ["LIVEKIT_URL"] = "   "
            s = config.voice_settings(local_file=local)
            check("blank environment value falls through to .env.local",
                  s.livekit_url == "wss://from-local.invalid")
            os.environ.pop("LIVEKIT_URL")

            os.environ["LIVEKIT_API_SECRET"] = "super-secret-value-xyz"
            s = config.voice_settings(local_file=local)
            status = s.public_status()
            check("configured once all three are present", s.configured is True)
            check("status contains no secret, key or URL",
                  "super-secret-value-xyz" not in repr(status)
                  and "local-key" not in repr(status)
                  and "from-local" not in repr(status))
            check("status reports camera disabled", status["camera"] is False)
            check("LLM is fixed to openai/gpt-4o", s.llm_model == "openai/gpt-4o")

            os.environ["SMARTHR_INTERVIEW_TOKEN_TTL_MINUTES"] = "-5"
            check("nonsense TTL falls back to the default",
                  config.voice_settings(local_file=local).token_ttl_minutes
                  == config.DEFAULT_TOKEN_TTL_MINUTES)
            os.environ.pop("SMARTHR_INTERVIEW_TOKEN_TTL_MINUTES")

            # export_livekit_environment never overwrites a variable already set.
            os.environ["LIVEKIT_URL"] = "wss://already-set.invalid"
            exported = config.export_livekit_environment(config.voice_settings(local_file=local))
            check("export leaves an existing variable alone",
                  os.environ["LIVEKIT_URL"] == "wss://already-set.invalid"
                  and "LIVEKIT_URL" not in exported)
            check("export returns names, not values",
                  all(name in config.LIVEKIT_VARIABLES for name in exported))
            os.environ.pop("LIVEKIT_API_SECRET", None)
            os.environ.pop("LIVEKIT_URL", None)
            os.environ.pop("LIVEKIT_API_KEY", None)
    finally:
        for name, value in saved.items():
            if value is None:
                os.environ.pop(name, None)
            else:
                os.environ[name] = value


def fake_settings():
    from app.ai.interview.config import (
        AGENT_NAME, DEFAULT_STT_MODEL, DEFAULT_TTS_MODEL, LLM_MODEL, VoiceSettings,
    )
    return VoiceSettings(
        livekit_url=FAKE_URL, api_key=FAKE_KEY, api_secret=FAKE_SECRET,
        stt_model=DEFAULT_STT_MODEL, tts_model=DEFAULT_TTS_MODEL, llm_model=LLM_MODEL,
        language="en", token_ttl_minutes=10, agent_name=AGENT_NAME,
    )


def verify_token(token: str):
    import base64
    import json

    from livekit import api

    claims = api.TokenVerifier(FAKE_KEY, FAKE_SECRET).verify(token)
    payload = token.split(".")[1]
    payload += "=" * (-len(payload) % 4)
    raw = json.loads(base64.urlsafe_b64decode(payload))
    return claims, raw


def assert_token(token: str, room: str, identity: str, label: str) -> None:
    from app.ai.interview.config import AGENT_NAME

    try:
        claims, raw = verify_token(token)
    except Exception as exc:
        check(f"{label}: signature verifies with the project secret", False, type(exc).__name__)
        return

    check(f"{label}: signature verifies with the project secret", True)
    try:
        api_bad = __import__("livekit.api", fromlist=["TokenVerifier"])
        api_bad.TokenVerifier(FAKE_KEY, "wrong-" + FAKE_SECRET).verify(token)
        check(f"{label}: a wrong secret is rejected", False)
    except Exception:
        check(f"{label}: a wrong secret is rejected", True)

    video = claims.video
    check(f"{label}: joins exactly its own room", video.room_join is True and video.room == room)
    check(f"{label}: microphone + camera are the publish sources",
          list(video.can_publish_sources or []) == ["microphone", "camera"])
    check(f"{label}: cannot publish data", video.can_publish_data is False)
    check(f"{label}: no admin/create/list grants",
          not video.room_admin and not video.room_create and not video.room_list)
    check(f"{label}: identity is the applicant id", claims.identity == identity)
    check(f"{label}: display name carries no PII", claims.name == "Applicant")
    check(f"{label}: no metadata", not claims.metadata)
    agents = list(claims.room_config.agents) if claims.room_config else []
    check(f"{label}: dispatches the interviewer by name",
          len(agents) == 1 and agents[0].agent_name == AGENT_NAME)
    check(f"{label}: dispatch carries no metadata", not (agents and agents[0].metadata))
    lifetime = raw.get("exp", 0) - raw.get("nbf", raw.get("iat", 0))
    check(f"{label}: lifetime is 10 minutes", 590 <= lifetime <= 610, str(lifetime))
    check(f"{label}: no email anywhere in the token", "@" not in repr(raw))


def test_token_offline() -> None:
    section("2. Token minted by the service")
    from app.models import Candidate
    from app.services import ai_interview_service as svc

    candidate = Candidate(id=987654, first_name="Test", last_name="Person",
                          email="should.not.appear@smarthr.test")
    result = svc.issue_room(candidate, settings=fake_settings())
    check("room name has the SmartHR prefix", result["room_name"].startswith(svc.ROOM_PREFIX))
    check("server URL returned for the browser", result["server_url"] == FAKE_URL)
    check("response carries no secret", FAKE_SECRET not in repr(result))
    check("response carries no email or name",
          "should.not.appear" not in repr(result) and "Person" not in repr(result))
    assert_token(result["participant_token"], result["room_name"], "applicant-987654", "service")

    other = svc.issue_room(candidate, settings=fake_settings())
    check("every session gets a new room", other["room_name"] != result["room_name"])


def test_not_configured() -> None:
    section("4. Not configured")
    from dataclasses import replace

    from app.models import Candidate
    from app.routers.ai_interview import ERROR_STATUS
    from app.services import ai_interview_service as svc

    empty = replace(fake_settings(), api_secret=None)
    try:
        svc.issue_room(Candidate(id=1), settings=empty)
        check("refuses without a secret", False)
    except svc.AiInterviewError as error:
        check("refuses without a secret", error.code == "not_configured")
        check("the refusal names the variable, not a value",
              "LIVEKIT_API_SECRET" in str(error) and FAKE_KEY not in str(error))
    check("not_configured maps to 503", ERROR_STATUS.get("not_configured") == 503)


def test_containment() -> None:
    section("5. Containment: the agent package never touches the database")
    forbidden = ("app.models", "app.database", "sqlalchemy")
    for path in sorted((ROOT / "app" / "ai" / "interview").glob("*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        imported = []
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                imported += [a.name for a in node.names]
            elif isinstance(node, ast.ImportFrom) and node.module:
                imported.append(node.module)
        bad = [m for m in imported if m.startswith(forbidden)]
        text = path.read_text(encoding="utf-8")
        check(f"{path.name}: no database import", not bad, ", ".join(bad))
        check(f"{path.name}: no session use", "SessionLocal" not in text and "db.commit" not in text)

    import app.ai.interview.worker as worker
    from app.ai.interview.config import AGENT_NAME
    check("worker registers the agent name the token dispatches to",
          worker.AGENT_NAME == AGENT_NAME)
    check("worker entry point is callable", callable(worker.interview_session))


def test_http() -> None:
    section("3. HTTP layer (own server on port 8043, fake LiveKit variables)")
    e2e.BASE = BASE

    applicant = e2e.register_applicant(APPLICANT, "Interview Tester")
    # Phase 4: a session is for one of the applicant's own interviews.
    interview = {"interview_id": e2e.ensure_ai_interview(applicant)["interview_id"]}
    tokens = {}
    for email, role in ((HR, 2), (MANAGER, 3), (EMPLOYEE, 4), (ADMIN, 1)):
        e2e.ensure_staff_account(email, role)
        tokens[role] = e2e.login(email)
    tokens[5] = applicant

    r = e2e.request("POST", "/ai-interview/session", json_body=interview)
    check("anonymous session request -> 401", r.status == 401, repr(r))
    r = e2e.request("GET", "/ai-interview/status")
    check("anonymous status request -> 401", r.status == 401, repr(r))

    for role in (1, 2, 3, 4):
        r = e2e.request("POST", "/ai-interview/session", token=tokens[role], json_body=interview)
        check(f"role {role} cannot open an applicant session -> 403", r.status == 403, repr(r))

    for role, expected in ((1, 200), (2, 200), (3, 403), (4, 403), (5, 200)):
        r = e2e.request("GET", "/ai-interview/status", token=tokens[role])
        check(f"role {role} status -> {expected}", r.status == expected, repr(r))

    r = e2e.request("GET", "/ai-interview/status", token=tokens[5])
    body = r.body if isinstance(r.body, dict) else {}
    check("status: configured through the environment", body.get("configured") is True, repr(r))
    check("status: models reported", body.get("models", {}).get("llm") == "openai/gpt-4o")
    check("status: no secret in the response",
          FAKE_SECRET not in r.raw and FAKE_KEY not in r.raw and FAKE_URL not in r.raw)

    invalid_language = e2e.request(
        "POST", "/ai-interview/session", token=tokens[5],
        json_body={**interview, "language": "fr"},
    )
    check("unsupported language -> 422", invalid_language.status == 422, repr(invalid_language))

    r = e2e.request("POST", "/ai-interview/session", token=tokens[5],
                    json_body={**interview, "language": "en"})
    check("applicant session with English -> 200", r.status == 200, repr(r))
    body = r.body if isinstance(r.body, dict) else {}
    identity = body.get("participant_identity", "")
    check("identity derived from the JWT, not the request", identity.startswith("applicant-"))
    check("session response has no secret", FAKE_SECRET not in r.raw)
    if body.get("participant_token"):
        assert_token(body["participant_token"], body["room_name"], identity, "http")

    arabic = e2e.request("POST", "/ai-interview/session", token=tokens[5],
                         json_body={**interview, "language": "ar"})
    check("applicant session with Arabic -> 200", arabic.status == 200, repr(arabic))
    arabic_body = arabic.body if isinstance(arabic.body, dict) else {}
    check("selected language is not added to the LiveKit token response",
          "language" not in arabic_body and FAKE_SECRET not in arabic.raw)

    from app.ai.interview.agent_auth import mint_agent_token
    plan = e2e.request("POST", "/ai-interview/agent/plan",
                       token=mint_agent_token(FAKE_KEY, FAKE_SECRET, arabic_body.get("room_name", "")))
    check("protected agent plan returns the stored Arabic language",
          plan.ok and plan.body.get("language") == "ar", repr(plan))

    legacy = e2e.request("POST", "/ai-interview/session", token=tokens[5], json_body=interview)
    check("legacy request without language remains accepted -> 200", legacy.status == 200, repr(legacy))
    legacy_plan = e2e.request(
        "POST", "/ai-interview/agent/plan",
        token=mint_agent_token(
            FAKE_KEY, FAKE_SECRET,
            legacy.body.get("room_name", "") if isinstance(legacy.body, dict) else "",
        ),
    )
    check("missing stored language is returned as null for worker fallback",
          legacy_plan.ok and legacy_plan.body.get("language") is None, repr(legacy_plan))

    r = e2e.request("POST", "/ai-interview/session", token=tokens[5],
                    json_body={**interview, "candidate_id": 1, "room_name": "hijack"})
    check("extra body fields (candidate, room) are refused -> 422", r.status == 422, repr(r))

    r = e2e.request("POST", "/ai-interview/session", token="not-a-jwt", json_body=interview)
    check("garbage JWT -> 401", r.status == 401, repr(r))

    r = e2e.request("GET", "/openapi.json")
    paths = r.body.get("paths", {}) if isinstance(r.body, dict) else {}
    # 114 after Phase 1; Phase 3 adds /agent/plan and three /questions paths;
    # Phase 4 adds /ai-interview/interviews, Phase 5 /ai-interview/agent/cv.
    check("openapi now serves 128 paths (Phase 12 intelligence; Phase 11.5.3 analytics; Phase 7 adds three, Phase 8 one, Phase 9 one)", len(paths) == 128, str(len(paths)))
    check("recruitment /interviews/ routes still present",
          "/interviews/" in paths and "/interviews/{interview_id}" in paths)


def main() -> int:
    print("SmartHR - AI Interview Phase 1 foundation tests")

    test_config()
    test_token_offline()
    with Server(PORT):
        test_http()
    test_not_configured()
    test_containment()

    print(f"\n{passed} passed, {len(failed)} failed")
    for failure in failed:
        print(f"  - {failure}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
